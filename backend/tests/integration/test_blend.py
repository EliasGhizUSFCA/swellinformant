class FakeProvider(ForecastProvider):
    """Synthetic constant sea state for every active spot (test-only)."""

    def __init__(
        self,
        code: str,
        family: str,
        hs: float,
        *,
        issued: datetime,
        step_hours: int = 1,
        partitions: bool = True,
        direction: float = 215.0,
        wind: float = 10.0,
        gust: float | None = None,
        gust_kind: str | None = None,
    ) -> None:
        self.code = code
        self.family = family
        self.hs = hs
        self.issued = issued
        self.step_hours = step_hours
        self.partitions = partitions
        self.direction = direction
        self.wind = wind
        self.gust = gust
        self.gust_kind = gust_kind

    def source_info(self) -> SourceInfo:
        return SourceInfo(
            self.code, self.code, "test", "w", "a", False, f"{self.code} data", "test", self.family
        )

    def current_run(self, now: datetime) -> RunInfo:
        return RunInfo(f"{self.code}:{self.issued:%Y%m%d%H}", self.issued, self.issued)

    def fetch(self, spots: list[SpotPoint], run: RunInfo) -> FetchResult:
        out = FetchResult()
        for p in spots:
            recs = []
            for h in range(0, 72, self.step_hours):
                v: dict[str, float | None] = {
                    "sig_wave_height_m": self.hs,
                    "wave_period_s": 14.0,
                    "wave_direction_deg": self.direction,
                    "wind_speed_kmh": self.wind,
                    "wind_direction_deg": 290.0,
                }
                if self.partitions:
                    v |= {
                        "primary_swell_height_m": self.hs * 0.9,
                        "primary_swell_period_s": 14.0,
                        "primary_swell_direction_deg": self.direction,
                        # No secondary or tertiary swell: absent partitions are None.
                        "wind_wave_height_m": self.hs * 0.3,
                        "wind_wave_period_s": 6.0,
                        "wind_wave_direction_deg": 290.0,
                    }
                extra: dict[str, object] = {}
                if self.gust is not None:
                    v["wind_gust_kmh"] = self.gust
                    if self.gust_kind:
                        extra["gust_kind"] = self.gust_kind
                recs.append(
                    ForecastRecord(
                        run.issued_at + timedelta(hours=h), v, period_kind="tp", extra=extra
                    )
                )
            out.records[p.spot_id] = recs
        return out


@pytest.fixture
def two_families(db: Session, few_spots: list[str], monkeypatch: pytest.MonkeyPatch) -> list[str]:
    codes = ["t_gfs", "t_ecmwf", "t_gfs_copy"]
    monkeypatch.setattr(blend, "configured_source_codes", lambda: codes)
    monkeypatch.setattr(queries, "configured_source_codes", lambda: codes)
    return codes


def _ingest(db: Session, *providers: FakeProvider) -> None:
    for prio, p in enumerate(providers):
        out = acquire_from_provider(db, p, now=NOW, priority=prio)
        assert out.status == "success", out


def _spot_id(db: Session, slug: str) -> int:
    return db.scalar(select(SurfSpot.id).where(SurfSpot.slug == slug))  # type: ignore[return-value]


def test_weights_and_interpolation_helpers() -> None:
    assert blend.correlated_weights([0.2, 0.2], ["ncep_gfs", "ecmwf_ifs"]) == pytest.approx(
        [0.5, 0.5]
    )
    w = blend.correlated_weights([0.1, 0.3], ["ncep_gfs", "ecmwf_ifs"])
    assert w[0] > 0.8 and sum(w) == pytest.approx(1.0)
    # strongly correlated and very unequal: the raw BLUE weight goes negative -> clipped
    w = blend.correlated_weights([0.1, 0.5], ["ncep_gfs", "ncep_gefs"])
    assert min(w) >= 0 and sum(w) == pytest.approx(1.0)


def test_blend_combines_independent_families(
    db: Session, two_families: list[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    # The prediction archive is optional and off by default since Swell 2.0
    # (PREDICTION_ARCHIVE_ENABLED); this test checks what it archives.
    monkeypatch.setattr(get_settings(), "prediction_archive_enabled", True)
    gfs = FakeProvider("t_gfs", "ncep_gfs", 2.0, issued=NOW - timedelta(hours=6))
    ec = FakeProvider(
        "t_ecmwf", "ecmwf_ifs", 3.0, issued=NOW - timedelta(hours=6), step_hours=3, partitions=False
    )
    copy = FakeProvider("t_gfs_copy", "ncep_gfs", 2.6, issued=NOW - timedelta(hours=6))
    _ingest(db, gfs, ec, copy)
    out = blend.build_blend(db, NOW)
    assert out.status == "success" and out.records > 0
    run = db.get(ForecastRun, out.run_id)
    assert run is not None and run.source.family == "blend" and run.source.kind == "blend"
    assert [m["code"] for m in run.details["members"]] == ["t_gfs", "t_ecmwf"]
    assert [m["code"] for m in run.details["cross_checks"]] == ["t_gfs_copy"]

    spot = _spot_id(db, "pipeline")
    rows = db.scalars(
        select(WaveForecast)
        .where(WaveForecast.run_id == run.id, WaveForecast.spot_id == spot)
        .order_by(WaveForecast.valid_time)
    ).all()
    # Equal leads and no verification: equal weights -> geometric mean of 2 and 3 m.
    assert rows[0].sig_wave_height_m == pytest.approx(math.sqrt(6.0), rel=1e-6)
    # Partitions come from the GFS member, scaled by Hs_blend / Hs_gfs.
    scale = math.sqrt(6.0) / 2.0
    assert rows[0].primary_swell_height_m == pytest.approx(1.8 * scale, rel=1e-6)
    assert rows[0].wave_period_kind == "tp"
    # ECMWF is 3-hourly: hour 1 is interpolated; the last GFS hours beyond ECMWF's last step
    # are not extrapolated, so they come from GFS alone.
    assert rows[1].sig_wave_height_m == pytest.approx(math.sqrt(6.0), rel=1e-6)
    assert rows[-1].sig_wave_height_m == pytest.approx(2.0)

    cmp_ = db.scalars(
        select(ForecastComparison)
        .where(ForecastComparison.blend_run_id == run.id, ForecastComparison.spot_id == spot)
        .order_by(ForecastComparison.valid_time)
    ).first()
    assert cmp_ is not None
    assert cmp_.hs_log_ratio_max == pytest.approx(math.log(1.5))
    assert "hs_disagree" in cmp_.flags  # 50 % apart > 40 % threshold
    assert "same_family_mismatch:t_gfs_copy" in cmp_.flags  # 2.6 vs 2.0 m from the same model
    assert cmp_.sources["t_gfs_copy"]["role"] == "cross_check"
    assert cmp_.sources["t_gfs"]["weight"] == pytest.approx(0.5)
    assert 0 < (cmp_.agreement or 0) < 1

    # idempotent
    assert blend.build_blend(db, NOW).status == "skipped"

    # The blend becomes authoritative once scored, and its uncertainty uses the disagreement.
    compute_pending_predictions(db)
    chosen = queries.latest_runs_by_spot(db, NOW)
    assert chosen[spot].id == run.id
    pred = db.scalar(
        select(SurfQualityPrediction).where(
            SurfQualityPrediction.run_id == run.id, SurfQualityPrediction.spot_id == spot
        )
    )
    assert pred is not None
    assert pred.components["uncertainty"]["source"] == "model_disagreement"
    # Every member's attribution (licence requirement) is shown with the blend, not the
    # cross-check's.
    shown = spot_forecast(db, db.get(SurfSpot, spot), now=NOW).source  # type: ignore[arg-type]
    assert shown is not None and shown.code == "blend"
    assert "t_gfs data" in shown.attribution and "t_ecmwf data" in shown.attribution
    assert "t_gfs_copy" not in shown.attribution
    assert pred.components["uncertainty"]["sigma_forecast"] == pytest.approx(
        math.log(1.5) / 2, abs=1e-3
    )

    # The archive holds 3-hourly rows of the authoritative run and is not rewritten.
    n = db.scalar(
        select(func.count()).select_from(PredictionArchive).where(PredictionArchive.spot_id == spot)
    )
    assert n == 24  # 72 h at 3-hourly steps
    assert db.scalar(select(PredictionArchive.source_code).limit(1)) == "blend"
    assert compute_pending_predictions(db)["archived"] == 0


def test_older_member_gets_less_weight(db: Session, two_families: list[str]) -> None:
    gfs = FakeProvider("t_gfs", "ncep_gfs", 2.0, issued=NOW - timedelta(hours=6))
    ec = FakeProvider("t_ecmwf", "ecmwf_ifs", 3.0, issued=NOW - timedelta(hours=18))
    _ingest(db, gfs, ec)
    run = db.get(ForecastRun, blend.build_blend(db, NOW).run_id)
    assert run is not None
    cmp_ = db.scalars(
        select(ForecastComparison).where(
            ForecastComparison.blend_run_id == run.id,
            ForecastComparison.valid_time == NOW + timedelta(hours=24),  # both members cover it
        )
    ).first()
    assert cmp_ is not None
    w = {k: v["weight"] for k, v in cmp_.sources.items()}
    assert w["t_gfs"] > w["t_ecmwf"] > 0
    assert run.issued_at == NOW - timedelta(hours=18)  # conservative issue time


