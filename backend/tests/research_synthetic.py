def synthetic_claim(
    variable: str, value: dict[str, Any] | None = None, agrees: bool | None = True
) -> dict[str, Any]:
    return {
        "variable": variable,
        "claim": f"SYNTHETIC claim about {variable} for tests.",
        "value": value,
        "excerpt": "SYNTHETIC excerpt, not quoted from any real page.",
        "agrees": agrees,
    }


def synthetic_source(
    key: str,
    source_type: str,
    claims: list[dict[str, Any]],
    *,
    publisher: str | None = None,
    year: int | None = 2020,
    url: str | None = None,
    accessed: str = ACCESSED,
    retrieval: str | None = None,
) -> dict[str, Any]:
    """``retrieval`` None leaves the field out (the format's default, "fetched")."""
    publisher = publisher or f"Synthetic Publisher {key}"
    host = publisher.lower().replace(" ", "-")
    out: dict[str, Any] = {
        "key": key,
        "title": f"SYNTHETIC test source {key}",
        "url": url if url is not None else f"https://{host}.example.org/{key}",
        "publisher": publisher,
        "source_type": source_type,
        "published_year": year,
        "accessed_at": accessed,
        "claims": claims,
    }
    if retrieval is not None:
        out["retrieval"] = retrieval
    return out


def synthetic_file(spots: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    return {
        "version": 1,
        "generated_at": "2026-10-11T00:00:00Z",
        "method": "SYNTHETIC evidence generated by the test suite; not real research.",
        "spots": {
            slug: {"notes": "SYNTHETIC test entry.", "sources": sources}
            for slug, sources in spots.items()
        },
    }


def parsed_sources(sources: list[dict[str, Any]]) -> list[EvidenceSource]:
    """Validate synthetic sources through the real parser and return them."""
    parsed = parse_evidence(synthetic_file({"synthetic-spot": sources}), {"synthetic-spot"})
    return list(parsed.spots["synthetic-spot"].sources)
