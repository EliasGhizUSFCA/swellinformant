_redis_down_until = 0.0


def _namespace() -> str:
    from app.services.public_cache import namespace

    return namespace()


def marker_key() -> str:
    return f"{_namespace()}:forecast-version:v1"


def first_served_key(version_id: int) -> str:
    return f"{_namespace()}:forecast-version:first-served:{int(version_id)}"


def seen_latency_key() -> str:
    return f"{_namespace()}:forecast-version:seen-latency"


def _client() -> redis.Redis | None:
    """The Redis client, or None while a recent failure keeps Redis out of the path (or
    the client cannot even be built, e.g. a malformed REDIS_URL)."""
    if time.monotonic() < _redis_down_until:
        return None
    try:
        return get_redis()
    except (redis.RedisError, ValueError) as exc:
        _failed("client not built", exc)
        return None


def _failed(what: str, exc: Exception) -> None:
    global _redis_down_until
    _redis_down_until = time.monotonic() + FAIL_OPEN_SECONDS
    logger.warning("Forecast version %s: Redis unavailable (%s)", what, type(exc).__name__)


def reset_fail_open() -> None:
    """Ask Redis again at once (tests, or after Redis came back)."""
    global _redis_down_until
    _redis_down_until = 0.0


def write_version_marker(payload: Mapping[str, Any]) -> bool:
    """Store the published version's payload (:func:`version_payload`) as the marker the
    version endpoint and the public snapshot cache read (no expiry: the next publication
    replaces it). False when Redis could not store it."""
    client = _client()
    if client is None:
        return False
    try:
        client.set(marker_key(), json.dumps(dict(payload), separators=(",", ":")))
    except redis.RedisError as exc:
        _failed("marker not stored", exc)
        return False
    return True


def read_version_marker() -> dict[str, Any] | None:
    """The stored marker payload; None when there is none, it is unreadable or Redis is
    unavailable (callers then read the database once and store it again)."""
    client = _client()
    if client is None:
        return None
    try:
        raw = client.get(marker_key())
    except redis.RedisError as exc:
        _failed("marker not read", exc)
        return None
    if not raw:
        return None
    try:
        data = json.loads(raw)
    except (TypeError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def note_first_served(version_id: int, now: datetime | None = None) -> bool:
    """Record when ``version_id`` was first served (SET NX): True when this call recorded
    it, False when it was recorded before or Redis is unavailable."""
    client = _client()
    if client is None:
        return False
    moment = _iso(now or utcnow())
    try:
        return bool(
            client.set(
                first_served_key(version_id), str(moment), nx=True, ex=FIRST_SERVED_TTL_SECONDS
            )
        )
    except redis.RedisError as exc:
        _failed("first-served time not stored", exc)
        return False


def first_served_at(version_id: int) -> datetime | None:
    """When ``version_id`` was first served (None when not recorded or Redis is down)."""
    client = _client()
    if client is None:
        return None
    try:
        raw = client.get(first_served_key(version_id))
    except redis.RedisError as exc:
        _failed("first-served time not read", exc)
        return None
    try:
        return _time(raw) if raw else None
    except ValueError:
        return None


def record_seen(
    version_id: int, now: datetime | None = None, *, published_at: datetime | None = None
) -> float | None:
    """A browser reports that it rendered ``version_id``: store ``now - published_at`` in
    seconds (at least 0) in the capped latency list and return it. ``published_at``
    defaults to the marker's; an id that is not the marker's version (unknown or old) is
    ignored (None), as is everything while Redis is unavailable."""
    now = now or utcnow()
    if published_at is None:
        marker = read_version_marker()
        if not marker or marker.get("version_id") != version_id:
            return None
        try:
            published_at = _time(marker.get("published_at"))
        except ValueError:
            return None
        if published_at is None:
            return None
    client = _client()
    if client is None:
        return None
    latency = max(0.0, (now - published_at).total_seconds())
    key = seen_latency_key()
    try:
        pipe = client.pipeline(transaction=True)
        pipe.lpush(key, f"{latency:.3f}")
        pipe.ltrim(key, 0, SEEN_LATENCY_SAMPLES - 1)
        pipe.execute()
    except redis.RedisError as exc:
        _failed("latency not stored", exc)
        return None
    return latency


def seen_latencies() -> list[float]:
    """The newest publication-to-browser latencies in seconds (newest first; at most
    :data:`SEEN_LATENCY_SAMPLES`; empty when Redis is unavailable)."""
    client = _client()
    if client is None:
        return []
    try:
        raw = client.lrange(seen_latency_key(), 0, SEEN_LATENCY_SAMPLES - 1)
    except redis.RedisError as exc:
        _failed("latencies not read", exc)
        return []
    out: list[float] = []
    for value in raw or ():
        try:
            out.append(float(value))
        except (TypeError, ValueError):
            continue
    return out
