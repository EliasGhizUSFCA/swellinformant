"""Forecast versions: stage, publish and serve the published forecast (design D7, D9-D11;
contracts C2-C4).

A refresh acquires, scores and validates, then **stages** a version
(:func:`stage_version`, status ``staging``) and **publishes** it in one transaction
(:func:`publish_version`): the published version becomes ``superseded`` and the staged one
``published``. Public reads serve only the published version: :func:`serving_runs` maps each
spot to the forecast run it is served from. A spot whose refresh failed keeps its previous
run with status ``stale`` (D9); spots a refresh did not touch (a retry of the failed spots
only) are carried over unchanged from the version it builds on. Before any version exists
(a database upgraded from Upgrade 4) :func:`serving_runs` falls back to the run selection
the public reads used before (``queries.latest_runs_by_spot``).

Freshness (D10, :func:`spot_freshness`): a spot is stale when its refresh failed while other
spots updated, when it has no data, or when a component's last update is older than that
model's update interval plus FORECAST_STALE_THRESHOLD_MINUTES (or its
FORECAST_STALE_THRESHOLD_MINUTES_BY_MODEL override).

Live updates (D11): :func:`version_payload` is the body of GET /api/forecasts/version (C4);
the Redis helpers keep it as the version marker, record when each version was first served
and the publication-to-browser latencies the clients report. Redis failures are swallowed
(logged by type only) and the helpers then answer as if Redis were empty, so a visitor
never sees a Redis error; after one, Redis is not asked again for
:data:`FAIL_OPEN_SECONDS`.

Lean imports only (the API and the refresh Function import this module): no pandas, scikit-
learn, SciPy, pyarrow, joblib or ecCodes (tests/unit/test_lean_imports.py). The run
selection (forecasts.queries) and the cache namespace (public_cache) are imported where they
are used, so either module may import this one.
"""

